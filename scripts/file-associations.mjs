import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const writeMode = process.argv.includes("--write");
if (!writeMode && !process.argv.includes("--check")) {
  throw new Error("Usage: node scripts/file-associations.mjs --check|--write");
}

const manifestPath = resolve(root, "packaging/file-associations.json");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const extensions = manifest.extensions;
const mimeTypes = manifest.linuxMimeTypes;

function assertSortedUnique(values, label, pattern) {
  if (!Array.isArray(values) || values.length === 0) {
    throw new Error(`${label} must be a non-empty array.`);
  }
  for (const value of values) {
    if (typeof value !== "string" || !pattern.test(value)) {
      throw new Error(`${label} contains an invalid value: ${String(value)}`);
    }
  }
  const expected = [...new Set(values)].sort();
  if (JSON.stringify(values) !== JSON.stringify(expected)) {
    throw new Error(`${label} must be sorted and contain no duplicates.`);
  }
}

assertSortedUnique(extensions, "extensions", /^[a-z0-9][a-z0-9+.-]*$/);
assertSortedUnique(mimeTypes, "linuxMimeTypes", /^[a-z0-9.+-]+\/[a-z0-9.+-]+$/);

const mimeLine = `${mimeTypes.join(";")};`;
function desktop(icon) {
  return `[Desktop Entry]\nType=Application\nName=Grayslate\nComment=A fast scratchpad for code, data, and quick thinking\nExec=Grayslate %F\nIcon=${icon}\nTerminal=false\nCategories=Development;TextEditor;\nKeywords=scratchpad;editor;JSON;CSV;developer;\nMimeType=${mimeLine}\nStartupNotify=true\nStartupWMClass=Grayslate\n`;
}

function nsisHooks() {
  const nsisQuote = String.raw`$\"`;
  const openWith = extensions.map((ext) =>
    `  WriteRegStr SHCTX "Software\\Classes\\.${ext}\\OpenWithProgids" "Grayslate.TextDocument" ""`
  ).join("\n");
  const supported = extensions.map((ext) =>
    `  WriteRegStr SHCTX "Software\\Classes\\Applications\\Grayslate.exe\\SupportedTypes" ".${ext}" ""`
  ).join("\n");
  const capabilities = extensions.map((ext) =>
    `  WriteRegStr SHCTX "Software\\Grayslate\\Capabilities\\FileAssociations" ".${ext}" "Grayslate.TextDocument"`
  ).join("\n");
  const removeOpenWith = extensions.map((ext) =>
    `  DeleteRegValue SHCTX "Software\\Classes\\.${ext}\\OpenWithProgids" "Grayslate.TextDocument"\n  DeleteRegKey /ifempty SHCTX "Software\\Classes\\.${ext}\\OpenWithProgids"`
  ).join("\n");

  return `; Generated by scripts/file-associations.mjs. Do not edit by hand.\n; Registers Grayslate as an optional handler only. It never writes an\n; extension's default value or the protected UserChoice keys.\n\n!macro NSIS_HOOK_POSTINSTALL\n  WriteRegStr SHCTX "Software\\Classes\\Grayslate.TextDocument" "" "Grayslate Document"\n  WriteRegStr SHCTX "Software\\Classes\\Grayslate.TextDocument\\DefaultIcon" "" '${nsisQuote}$INSTDIR\\Grayslate.exe${nsisQuote},0'\n  WriteRegStr SHCTX "Software\\Classes\\Grayslate.TextDocument\\shell\\open\\command" "" '${nsisQuote}$INSTDIR\\Grayslate.exe${nsisQuote} ${nsisQuote}%1${nsisQuote}'\n  WriteRegStr SHCTX "Software\\Classes\\Applications\\Grayslate.exe" "FriendlyAppName" "Grayslate"\n  WriteRegStr SHCTX "Software\\Classes\\Applications\\Grayslate.exe\\DefaultIcon" "" '${nsisQuote}$INSTDIR\\Grayslate.exe${nsisQuote},0'\n  WriteRegStr SHCTX "Software\\Classes\\Applications\\Grayslate.exe\\shell\\open\\command" "" '${nsisQuote}$INSTDIR\\Grayslate.exe${nsisQuote} ${nsisQuote}%1${nsisQuote}'\n${openWith}\n${supported}\n  WriteRegStr SHCTX "Software\\Grayslate\\Capabilities" "ApplicationName" "Grayslate"\n  WriteRegStr SHCTX "Software\\Grayslate\\Capabilities" "ApplicationDescription" "A fast scratchpad for code, data, and quick thinking."\n  WriteRegStr SHCTX "Software\\Grayslate\\Capabilities" "ApplicationIcon" '$INSTDIR\\Grayslate.exe,0'\n${capabilities}\n  WriteRegStr SHCTX "Software\\RegisteredApplications" "Grayslate" "Software\\Grayslate\\Capabilities"\n  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'\n!macroend\n\n!macro NSIS_HOOK_PREUNINSTALL\n${removeOpenWith}\n  DeleteRegValue SHCTX "Software\\RegisteredApplications" "Grayslate"\n  DeleteRegKey SHCTX "Software\\Grayslate\\Capabilities"\n  DeleteRegKey /ifempty SHCTX "Software\\Grayslate"\n  DeleteRegKey SHCTX "Software\\Classes\\Applications\\Grayslate.exe"\n  DeleteRegKey SHCTX "Software\\Classes\\Grayslate.TextDocument"\n  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'\n!macroend\n`;
}

const generated = new Map([
  [resolve(root, "packaging/linux/app.grayslate.Grayslate.desktop"), desktop("app.grayslate.Grayslate")],
  [resolve(root, "packaging/linux/Grayslate.appimage.desktop"), desktop("Grayslate")],
  [resolve(root, "packaging/windows/file-associations.nsh"), nsisHooks()],
]);

const macConfigPath = resolve(root, "src-tauri/tauri.macos.conf.json");
const macConfig = JSON.parse(await readFile(macConfigPath, "utf8"));
const expectedMacAssociations = [{
  ext: extensions,
  name: "Grayslate Document",
  role: "Editor",
  rank: "Alternate",
}];

if (writeMode) {
  for (const [path, content] of generated) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
  macConfig.bundle.fileAssociations = expectedMacAssociations;
  await writeFile(macConfigPath, `${JSON.stringify(macConfig, null, 2)}\n`);
  console.log(`Generated associations for ${extensions.length} extensions.`);
} else {
  const errors = [];
  for (const [path, expected] of generated) {
    const actual = await readFile(path, "utf8").catch(() => "");
    if (actual !== expected) errors.push(path.slice(root.length + 1));
  }
  if (JSON.stringify(macConfig.bundle.fileAssociations) !== JSON.stringify(expectedMacAssociations)) {
    errors.push("src-tauri/tauri.macos.conf.json");
  }
  const baseConfig = JSON.parse(await readFile(resolve(root, "src-tauri/tauri.conf.json"), "utf8"));
  if (baseConfig.bundle.fileAssociations !== undefined) {
    errors.push("src-tauri/tauri.conf.json (fileAssociations must remain platform-specific)");
  }
  const windowsConfig = JSON.parse(await readFile(resolve(root, "src-tauri/tauri.windows.conf.json"), "utf8"));
  if (windowsConfig.bundle?.windows?.nsis?.installerHooks !== "../packaging/windows/file-associations.nsh") {
    errors.push("src-tauri/tauri.windows.conf.json");
  }
  const appImageConfig = JSON.parse(await readFile(resolve(root, "src-tauri/tauri.appimage.conf.json"), "utf8"));
  if (appImageConfig.bundle?.linux?.deb?.desktopTemplate !== "../packaging/linux/Grayslate.appimage.desktop") {
    errors.push("src-tauri/tauri.appimage.conf.json");
  }
  const releaseWorkflow = await readFile(resolve(root, ".github/workflows/release.yml"), "utf8");
  if (!releaseWorkflow.includes("system_config: --config src-tauri/tauri.appimage.conf.json")) {
    errors.push(".github/workflows/release.yml (AppImage config is not selected)");
  }
  const dbusName = "app.grayslate.Grayslate.SingleInstance";
  const flatpak = await readFile(resolve(root, "packaging/flatpak/app.grayslate.Grayslate.yml.in"), "utf8");
  if (!flatpak.includes(`--own-name=${dbusName}`) || !flatpak.includes(`--talk-name=${dbusName}`)) {
    errors.push("packaging/flatpak/app.grayslate.Grayslate.yml.in");
  }
  const snap = await readFile(resolve(root, "snap/snapcraft.yaml"), "utf8");
  if ((snap.match(new RegExp(dbusName.replaceAll(".", "\\."), "g")) ?? []).length !== 2) {
    errors.push("snap/snapcraft.yaml");
  }
  if (errors.length > 0) {
    throw new Error(`File-association metadata is stale: ${errors.join(", ")}. Run pnpm run generate:file-associations.`);
  }
  console.log(`Verified associations for ${extensions.length} extensions.`);
}
